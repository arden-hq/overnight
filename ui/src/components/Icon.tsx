export function Icon({ name, size = 14, className }: { name: string; size?: number; className?: string }) {
  const C = ICONS[name] ?? Dot;
  return <C className={className} size={size} strokeWidth={1.75} aria-hidden />;
}

export function serviceIcon(app: string | undefined): string {
  if (!app) return "records";
  return ICONS[app] ? app : "records";
}
