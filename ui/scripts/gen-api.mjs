import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const check = process.argv.includes("--check");
const schemaPath = new URL("../src/api/schema.json", import.meta.url);
const typesPath = new URL("../src/api/types.ts", import.meta.url);
const saved = readFileSync(schemaPath, "utf8");
if (check) {
  const overnight = fileURLToPath(new URL("../../.venv/bin/overnight", import.meta.url));
  const current = execFileSync(overnight, ["serve", "--print-schema"], { encoding: "utf8" });
  if (current !== saved) {
    console.error("src/api/schema.json differs from `overnight serve --print-schema`: run `npm run gen:api`.");
    process.exit(1);
  }
  console.log("src/api/schema.json matches `overnight serve --print-schema`");
}
const schema = JSON.parse(saved);

for (const name of ["JsonValue", "FrozenJson", "JsonObject"]) {
  if (schema.$defs?.[name]) schema.$defs[name] = name === "JsonObject" ? { title: name, type: "object", additionalProperties: true, tsType: "{ [key: string]: unknown }" } : { title: name, tsType: "unknown" };
}

// Property titles ("Agent Kind") would each become a named alias; only the models keep names.
const untitle = (node, keep) => {
  if (Array.isArray(node)) return node.forEach((item) => untitle(item, false));
  if (node === null || typeof node !== "object") return;
  if (!keep) delete node.title;
  for (const [key, value] of Object.entries(node)) {
    if (key === "$defs") for (const def of Object.values(value)) untitle(def, true);
    else if (key === "properties") for (const prop of Object.values(value)) untitle(prop, false);
    else untitle(value, false);
  }
};
untitle(schema, true);

const generated = await compile(schema, "OvernightWorkbenchApi", {
  bannerComment: "/* Generated by scripts/gen-api.mjs from src/api/schema.json. Do not edit; run `npm run gen:api`. */",
  additionalProperties: false,
  unreachableDefinitions: true,
  format: true,
  style: { semi: true, printWidth: 120 },
});

const body = generated.replace(/\/\*\*\n \* This interface was referenced by[^/]*\*\/\n/g, "");

if (check) {
  const current = readFileSync(typesPath, "utf8");
  if (current !== body) {
    console.error("src/api/types.ts is stale: run `npm run gen:api`.");
    process.exit(1);
  }
  console.log("src/api/types.ts matches src/api/schema.json");
} else {
  writeFileSync(typesPath, body);
  console.log("wrote src/api/types.ts");
}
